export const LANGUAGES = [
  { id: 'en', name: 'English' },
  { id: 'ru', name: 'Русский' },
];
const DICTS = { en, ru };

function stored() {
  try {
    const v = localStorage.getItem('lang');
    return v && Object.hasOwn(DICTS, v) ? v : 'en';
  } catch {
    return 'en';
  }
}

let lang = stored();
const subscribers = new Set();

export function setLang(next) {
  if (!Object.hasOwn(DICTS, next) || next === lang) return;
  lang = next;
  try {
    localStorage.setItem('lang', next);
  } catch {
    // Without storage the choice simply lasts until the page reloads.
  }
  document.documentElement.lang = next;
  for (const fn of subscribers) fn();
}

export function useLang() {
  return useSyncExternalStore(
    (fn) => {
      subscribers.add(fn);
      return () => subscribers.delete(fn);
    },
    () => lang,
  );
}

/** For dates and numbers in the chosen language rather than the system's. */
export function locale() {
  return lang;
}

export function has(key) {
  return Object.hasOwn(DICTS[lang], key) || Object.hasOwn(en, key);
}

/** @param {string} key @param {Record<string, string | number>} [vars] */
export function t(key, vars) {
  const text = DICTS[lang][key] ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : text;
}

document.documentElement.lang = lang;
